#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md (ADR-045).

Rust crates: the normal and build dependencies of the `ttnr` binary for the
shipped target (aarch64-apple-darwin, `cargo tree`), with licences from
`cargo metadata` and the licence files found in each crate's source.
Native libraries: what libmpv links (recursively, `otool -L`) from Homebrew,
with Homebrew's licence metadata (`brew info --json=v2`, read-only).

  scripts/notices.py           write THIRD_PARTY_NOTICES.md
  scripts/notices.py --check   exit 1 if the file is out of date
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
TARGET = "aarch64-apple-darwin"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.I)


def run(*cmd):
    return subprocess.run(cmd, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def rust_crates():
    # The package set comes from `cargo tree` (what the binary is built
    # from); `cargo metadata` supplies licences and source directories.
    tree = run("cargo", "tree", "--locked", "-e", "normal,build", "--target", TARGET,
               "-p", "ttnr", "--prefix", "none", "--format", "{p}")
    wanted = set()
    for line in tree.splitlines():
        m = re.match(r"^(\S+) v(\S+)", line)
        if m:
            wanted.add((m.group(1), m.group(2)))
    meta = json.loads(run("cargo", "metadata", "--format-version", "1",
                          "--filter-platform", TARGET, "--locked"))
    workspace = set(meta["workspace_members"])
    crates = []
    for p in meta["packages"]:
        if p["id"] in workspace or (p["name"], p["version"]) not in wanted:
            continue
        src = pathlib.Path(p["manifest_path"]).parent
        texts = []
        for f in sorted(src.iterdir()):
            if f.is_file() and LICENSE_FILE.match(f.name):
                texts.append((f.name, f.read_text(errors="replace").strip()))
        crates.append({"name": p["name"], "version": p["version"],
                       "license": p.get("license") or "see licence file",
                       "repository": p.get("repository") or "", "texts": texts})
    return sorted(crates, key=lambda c: (c["name"], c["version"]))


def libmpv():
    local = ROOT / "third_party/mpv/prefix/lib/libmpv.2.dylib"
    if local.exists():
        return str(local)
    prefix = run("brew", "--prefix", "mpv").strip()
    return f"{prefix}/lib/libmpv.2.dylib"


def native_formulae():
    """Homebrew formulae whose libraries libmpv loads, plus mpv itself."""
    formulae, seen, todo = {"mpv"}, set(), [libmpv()]
    while todo:
        lib = todo.pop()
        if lib in seen:
            continue
        seen.add(lib)
        for line in run("otool", "-L", lib).splitlines()[1:]:
            path = line.strip().split(" (")[0]
            m = re.match(r"/opt/homebrew/(?:opt|Cellar)/([^/]+)/", path)
            if m:
                formulae.add(m.group(1))
                todo.append(path)
    info = json.loads(run("brew", "info", "--json=v2", *sorted(formulae)))
    out = []
    for f in info["formulae"]:
        out.append({"name": f["name"], "version": f["versions"]["stable"],
                    "license": f.get("license") or "unknown",
                    "homepage": f.get("homepage") or ""})
    return sorted(out, key=lambda f: f["name"])


def render():
    crates, native = rust_crates(), native_formulae()
    lines = [
        "# Third-party notices",
        "",
        "Generated by `scripts/notices.py` – do not edit. ttnr's own code is",
        "BSD-2-Clause (`LICENSE`).",
        "",
        "A compiled `ttnr` binary contains the Rust crates below (statically",
        "linked) and loads the native libraries below at run time. libmpv and",
        "FFmpeg from Homebrew are GPL builds, so a distributed binary is, as a",
        "combined work, under GPL-3.0-or-later: ship the GPL-3.0 text and offer",
        "the corresponding source of the GPL parts. `libmpv2`/`libmpv2-sys` are",
        "LGPL-2.1-only; LGPL-2.1 section 3 lets a copy be put under the GPL",
        "version 2 or later instead, which the combined work does (ADR-045).",
        "",
        f"## Native libraries (Homebrew, loaded at run time)",
        "",
        "| Library | Version | Licence | Homepage |",
        "|---|---|---|---|",
    ]
    for f in native:
        lines.append(f"| {f['name']} | {f['version']} | {f['license']} | {f['homepage']} |")
    lines += [
        "",
        "Their licence texts are installed by Homebrew with each formula",
        "(`$(brew --prefix <name>)`).",
        "",
        f"## Rust crates ({len(crates)}, target {TARGET})",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
    ]
    for c in crates:
        lines.append(f"| {c['name']} | {c['version']} | {c['license']} |")
    lines += ["", "## Licence texts of the Rust crates", ""]
    # Identical texts are printed once, with every crate that ships them.
    by_text = {}
    for c in crates:
        for name, text in c["texts"]:
            by_text.setdefault(text, []).append(f"{c['name']} {c['version']} ({name})")
    for text, users in sorted(by_text.items(), key=lambda kv: kv[1][0]):
        lines += ["<details><summary>" + ", ".join(users) + "</summary>", "",
                  "```text", text, "```", "", "</details>", ""]
    missing = [c for c in crates if not c["texts"]]
    if missing:
        lines += ["Crates whose package contains no licence file (licence per their",
                  "metadata above; the texts are in their repositories – include them",
                  "when distributing a binary):", ""]
        for c in missing:
            lines.append(f"- {c['name']} {c['version']} ({c['license']}): {c['repository']}")
        lines.append("")
    return "\n".join(lines)


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("THIRD_PARTY_NOTICES.md is out of date: run scripts/notices.py", file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
